"""Build index.html (Shop) and hello.html from the templates in this folder.

Run from anywhere:  python3 build/build.py
Index.html: embeds 4-shade particle targets + 4 colourways per product.

Colourway 1 is the original photo. Colourways 2-4 are generated by a duotone
recolour of the product pixels (background stays white), so one photo
simulates four items.
"""
import base64, io, json, os
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))   # build/ (sources)
SITE = os.path.dirname(HERE)                          # repo root (published pages)

# product id -> [(colourway name, hex or None for original), ...]
COLOURWAYS = {
    "t-shirt":  [("Jet", None), ("Sage", "#7f9a7a"), ("Brick", "#a4503a"), ("Ocean", "#3d5f8a")],
    "shirt":    [("Red Check", None), ("Forest Check", "#2f6b4a"), ("Navy Check", "#2d4a7a"), ("Mustard Check", "#c49a2c")],
    "crop_top": [("Blush", None), ("Butter", "#e8c95a"), ("Lilac", "#a98bd6"), ("Mint", "#6fc4a0")],
    "skirt":    [("Washed Black", None), ("Indigo", "#34508a"), ("Sand", "#b8a07a"), ("Olive", "#6b6e3e")],
    "pant":     [("Slate", None), ("Burgundy", "#7a2c3a"), ("Moss", "#5d6b3a"), ("Camel", "#b08350")],
    "shoes":    [("Black", None), ("Stone", "#9a958a"), ("Navy", "#2c3b5a"), ("Clay", "#a8644a")],
    "cap":      [("Glacier", None), ("Coral", "#e07a5f"), ("Khaki", "#a89a6a"), ("Charcoal", "#3a3a3a")],
    "specs":    [("Black Gold", None), ("Tortoise", "#8a5a2b"), ("Rose", "#c98a8a"), ("Emerald", "#2f6e5a")],
}


def hex_rgb(h):
    return np.array([int(h[i:i + 2], 16) for i in (1, 3, 5)], np.float32) / 255


def recolour(img, hexcol):
    a = np.asarray(img).astype(np.float32) / 255
    # soft product mask: how far the pixel is from white
    m = np.clip(((1 - a).max(axis=2) - 0.04) / 0.10, 0, 1)[..., None]
    lum = a @ np.array([0.299, 0.587, 0.114], np.float32)
    inside = m[..., 0] > 0.5
    lo, hi = np.percentile(lum[inside], [2, 98]) if inside.any() else (0, 1)
    ln = np.clip((lum - lo) / max(hi - lo, 1e-3), 0, 1)[..., None]
    ln = 0.12 + 0.76 * ln                       # keep shadows and highlights inside the tint
    c = hex_rgb(hexcol)
    dark, light = c * 0.30, c + (1 - c) * 0.55
    col = dark + (light - dark) * ln
    out = 1 + (col - 1) * m                      # blend onto white by the mask
    return Image.fromarray((np.clip(out, 0, 1) * 255).astype(np.uint8))


def jpeg_uri(img, q=80):
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=q, optimize=True, progressive=True)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()


def png_uri(path):
    with open(path, "rb") as f:
        return "data:image/png;base64," + base64.b64encode(f.read()).decode()


targets, photos, colourways = {}, {}, {}
for pid, ways in COLOURWAYS.items():
    targets[pid] = png_uri(os.path.join(HERE, "out", pid + ".png"))
    base = Image.open(os.path.join(HERE, "src", pid + ".jpg")).convert("RGB")
    # crop to the product (+ margin) so every photo fills its card the same way
    arr = np.asarray(base).astype(np.int16)
    ys, xs = np.where((255 - arr).max(axis=2) > 28)
    pad = int(0.06 * max(np.ptp(xs), np.ptp(ys)))
    base = base.crop((max(0, xs.min() - pad), max(0, ys.min() - pad),
                      min(base.width, xs.max() + pad), min(base.height, ys.max() + pad)))
    base.thumbnail((640, 640), Image.LANCZOS)
    photos[pid] = [jpeg_uri(base if h is None else recolour(base, h)) for _, h in ways]
    colourways[pid] = [{"name": n, "hex": h} for n, h in ways]

with open(os.path.join(HERE, "template.html"), encoding="utf-8") as f:
    html = f.read()
for key, val in (("__TARGETS__", targets), ("__PHOTOS__", photos), ("__COLOURWAYS__", colourways)):
    assert key in html, key
    html = html.replace(key, json.dumps(val))
with open(os.path.join(SITE, "index.html"), "w", encoding="utf-8") as f:
    f.write(html)
print("index.html", os.path.getsize(os.path.join(SITE, "index.html")), "bytes")

